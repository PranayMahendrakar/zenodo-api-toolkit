def html_target_ok(path, force):
    """Refuse to clobber a file this tool did not generate, unless --force."""
    if force or not os.path.isfile(path):
        return True
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            head = fh.read(4096)
    except OSError:
        return True          # write_html will report the real problem
    return HTML_MARKER in head


