def collect(session, record_ids, labels, auth=False):
    """Fetch stats for each record id. Returns the list of normalised rows."""
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    out = []
    for rid in record_ids:
        rec = fetch_record(session, rid, auth=auth)
        if not isinstance(rec, dict):
            note(f"  [{rid}] skipped -- record not readable")
            continue
        meta = rec.get("metadata") or {}
        stats = rec.get("stats") or {}
        title = meta.get("title") or rec.get("title") or labels.get(str(rid)) or ""
        pub = meta.get("publication_date") or ""
        row = {
            "timestamp": stamp,
            "record_id": str(rid),
            "title": str(title),
            "publication_date": str(pub),
            "views": as_int(stats.get("views")),
            "downloads": as_int(stats.get("downloads")),
            "unique_views": as_int(stats.get("unique_views")),
            "unique_downloads": as_int(stats.get("unique_downloads")),
        }
        row["days"] = days_since(pub)
        out.append(row)
        note(f"  [{rid}] views={row['views']:,} downloads={row['downloads']:,}"
             f"  {clip(title, 40)}")
    return out


def main():
    global JSON_MODE

    ap = argparse.ArgumentParser(
        description="Read-only metrics tracker for your published Zenodo records.",
        epilog="This tool never writes to Zenodo -- it issues GET requests only.")
    ap.add_argument("--json", action="store_true",
                    help="dump the raw collected data to stdout instead of a table")
    ap.add_argument("--csv", metavar="PATH", default=DEFAULT_CSV,
                    help="history CSV to append to (default: %(default)s)")
    ap.add_argument("--html", metavar="PATH",
                    help="also write a self-contained HTML dashboard to PATH")
    ap.add_argument("--no-history", action="store_true",
                    help="do not append this run to the history CSV")
    ap.add_argument("--record", metavar="ID", action="append", default=[],
                    help="track this public record id instead of your own "
                         "depositions (repeatable, needs no token)")
    ap.add_argument("--force", action="store_true",
                    help="allow --html to overwrite a file this tool did not write")
    args = ap.parse_args()
    JSON_MODE = args.json

    session = requests.Session()
    note(f"host    : {BASE}")

    labels = {}
    authed = False
    if args.record:
        record_ids = [str(x).strip() for x in args.record if str(x).strip()]
        if not record_ids:
            note("no usable record ids were given.")
            return 2
        note(f"records : {len(record_ids)} explicit id(s), public read only")
    else:
        if not TOKEN:
            write_line(sys.stderr,
                       "ZENODO_TOKEN is not set in this shell, so your deposition "
                       "list cannot be read.\nSet it, or pass --record ID to track "
                       "specific public records without a token.")
            return 2
        note(f"token   : {mask(TOKEN)}")
        note("GET /api/deposit/depositions")
        deps = fetch_depositions(session)
        if deps is None:
            return 1
        published = [d for d in deps if d.get("state") == "done"]
        note(f"  {len(deps)} deposition(s), {len(published)} published")
        if not published:
            note("nothing published yet -- no metrics to track.")
            return 0
        # The depositions call already proved the token is good, so record
        # reads can carry it too and use the higher authenticated rate cap.
        authed = True
        record_ids = []
        for d in published:
            rid = str(d.get("record_id") or d.get("id") or "").strip()
            if not rid:
                note("  skipping a published deposition with no id")
                continue
            record_ids.append(rid)
            labels[rid] = d.get("title") or ""

    note("GET /api/records/:id")
    records = collect(session, record_ids, labels, auth=authed)
    if not records:
        note("no readable records -- nothing to report.")
        return 1

    history = load_history(args.csv)
    prev, prev_ts = previous_snapshot(history)

    wrote = False
    if not args.no_history:
        wrote = append_history(args.csv, records)

    records.sort(key=lambda r: (r["downloads"], r["views"]), reverse=True)

    if args.json:
        json.dump({
            "base": BASE,
            "generated": records[0]["timestamp"],
            "previous_run": prev_ts,
            "history_csv": os.path.abspath(args.csv) if wrote else None,
            "records": [
                dict(r,
                     downloads_per_day=per_day(r["downloads"], r["days"]),
                     delta_views=(r["views"] - prev[r["record_id"]]["views"]
                                  if r["record_id"] in prev else None),
                     delta_downloads=(r["downloads"] - prev[r["record_id"]]["downloads"]
                                      if r["record_id"] in prev else None))
                for r in records
            ],
        }, sys.stdout, indent=2)
        sys.stdout.write("\n")
    else:
        show()
        render_table(records, prev, prev_ts)

    if wrote:
        note(f"appended {len(records)} row(s) to {os.path.abspath(args.csv)}")
    elif args.no_history:
        note("history not updated (--no-history)")

    if args.html:
        if not html_target_ok(args.html, args.force):
            note(f"refusing to overwrite {os.path.abspath(args.html)}: it was not "
                 "written by this tool.")
            note("pick another --html path, or pass --force to overwrite it.")
            return 1
        all_rows = history + records
        if write_html(args.html, records, prev, prev_ts, all_rows,
                      records[0]["timestamp"]):
            note(f"wrote dashboard {os.path.abspath(args.html)}")

    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.exit(130)
