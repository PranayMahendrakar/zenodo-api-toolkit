def ascii_safe(text):
    """Fold arbitrary Unicode down to plain ASCII for console output.

    Record titles and API error bodies come back from the server and routinely
    contain accents, typographic dashes and non-Latin scripts. A Windows
    console is cp1252 and raises UnicodeEncodeError on anything it cannot map,
    which would kill the run with a traceback instead of printing the report,
    so nothing reaches the terminal without passing through here. The CSV and
    the HTML dashboard are UTF-8 and keep the original text intact.
    """
    s = str(text).translate(TRANSLIT)
    # Decompose so accented letters keep their base form (e -> e, a -> a),
    # then drop the combining marks that are left over.
    s = "".join(c for c in unicodedata.normalize("NFKD", s)
                if not unicodedata.combining(c))
    return s.encode("ascii", "replace").decode("ascii")


def write_line(stream, msg):
    stream.write(ascii_safe(msg) + "\n")
    stream.flush()


def note(msg=""):
    """Progress text. Kept off stdout in --json mode so the dump stays clean."""
    write_line(sys.stderr if JSON_MODE else sys.stdout, msg)


def show(msg=""):
    """Report output. Always stdout, always ASCII."""
    write_line(sys.stdout, msg)


def as_int(value):
    """Zenodo stats are ints today; tolerate floats, numeric strings and nulls."""
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return 0


def mask(token):
    if not token:
        return "(none)"
    if len(token) <= 10:
        return "*" * len(token)
    return f"{token[:6]}...{token[-4:]} ({len(token)} chars)"


# --------------------------------------------------------------- http (GET only)

_last_request = [0.0]        # monotonic clock reading of the previous GET


def throttle(auth):
    """Space requests out so a long run stays inside the published budget.

    Spacing is measured from the previous request rather than slept blindly
    after it, so time already spent waiting on the network counts towards the
    gap and a slow connection is not penalised twice.
    """
    gap = MIN_GAP_AUTH if auth else MIN_GAP_GUEST
    wait = gap - (time.monotonic() - _last_request[0])
    if wait > 0:
        time.sleep(wait)
    _last_request[0] = time.monotonic()


def observe_limits(r):
    """Pause when the server says the current rate window is nearly spent."""
    try:
        remaining = int(r.headers.get("x-ratelimit-remaining", ""))
        reset = int(r.headers.get("x-ratelimit-reset", ""))
    except (TypeError, ValueError):
        return
    if remaining > 3:
        return
    wait = min(max(reset - time.time(), 0.0) + 1.0, MAX_BACKOFF)
    if wait > 0:
        note(f"  rate budget nearly spent ({remaining} left), pausing {wait:.0f}s ...")
        time.sleep(wait)


def retry_delay(r, attempt):
    """Seconds to wait after a 429.

    Retry-After is legally either a count of seconds or an HTTP date, and a
    bare int() on the date form would raise straight through the caller.
    """
    raw = (r.headers.get("Retry-After") or "").strip()
    wait = None
    if raw:
        try:
            wait = float(int(raw))
        except ValueError:
            try:
                when = email.utils.parsedate_to_datetime(raw)
                if when is not None:
                    if when.tzinfo is None:
                        when = when.replace(tzinfo=datetime.timezone.utc)
                    now = datetime.datetime.now(datetime.timezone.utc)
                    wait = (when - now).total_seconds()
            except (TypeError, ValueError, OverflowError):
                wait = None
    if wait is None or wait <= 0:
        wait = 5.0 * attempt
    return min(wait, MAX_BACKOFF)


def get(session, url, params=None, auth=False, tries=3):
    """GET with 429 backoff. Returns the decoded body, or None after reporting."""
    headers = {"Authorization": f"Bearer {TOKEN}"} if auth and TOKEN else {}
    for attempt in range(1, tries + 1):
        throttle(auth)
        try:
            r = session.get(url, params=params, headers=headers, timeout=60)
        except requests.RequestException as exc:
            note(f"  network error on {url}: {exc.__class__.__name__}")
            return None
        if r.status_code == 429:
            wait = retry_delay(r, attempt)
            note(f"  rate limited (429), waiting {wait:.0f}s ...")
            time.sleep(wait)
            continue
        observe_limits(r)
        if r.status_code == 200:
            try:
                return r.json()
            except ValueError:
                note(f"  {url} returned non-JSON: {r.text[:200]}")
                return None
        note(f"  HTTP {r.status_code} on {url}")
        body = r.text.strip().replace("\n", " ")
        if body:
            note(f"    {body[:300]}")
        if auth and r.status_code in (400, 401, 403):
            # Zenodo does not reject a bad Bearer token outright -- it drops
            # you to guest access, so a stale token shows up as whatever guests
            # are not allowed to do (e.g. "page size cannot be greater than
            # 25") rather than as a straightforward 401.
            note("    the token was not accepted, so this ran as a guest.")
            note("    check that ZENODO_TOKEN is current, has the "
                 "deposit:actions/deposit:write scopes, and belongs to "
                 f"{BASE} -- sandbox and production tokens are not "
                 "interchangeable.")
        return None
    note(f"  gave up on {url} after {tries} attempts")
    return None


def fetch_depositions(session):
    """GET /api/deposit/depositions, paginated until a short page comes back."""
    out, page = [], 1
    while page <= MAX_PAGES:
        batch = get(session, f"{BASE}/api/deposit/depositions",
                    params={"size": PAGE_SIZE, "page": page}, auth=True)
        if batch is None:
            return None
        if not isinstance(batch, list):
            note(f"  unexpected depositions payload: {str(batch)[:200]}")
            return None
        out.extend(batch)
        note(f"  page {page}: {len(batch)} deposition(s)")
        if len(batch) < PAGE_SIZE:
            return out
        page += 1
    note(f"  stopping at the {MAX_PAGES}-page ceiling ({len(out)} so far)")
    return out


def fetch_record(session, record_id, auth=False):
    """GET /api/records/:id -- public endpoint; a token only raises the rate cap."""
    return get(session, f"{BASE}/api/records/{record_id}", auth=auth)


# ------------------------------------------------------------------------ dates

def days_since(publication_date):
    """Whole days from an ISO 'YYYY-MM-DD' to today. None if unparseable."""
    if not publication_date:
        return None
    try:
        parts = [int(x) for x in str(publication_date)[:10].split("-")]
        pub = datetime.date(parts[0], parts[1], parts[2])
    except (ValueError, TypeError, IndexError):
        return None
    return (datetime.date.today() - pub).days


def per_day(downloads, days):
    """Downloads per day. Same-day (or future-dated) publications count as 1 day."""
    if days is None:
        return None
    return downloads / float(max(days, 1))


# ------------------------------------------------------------------------- csv

def load_history(path):
    if not os.path.isfile(path):
        return []
    rows = []
    try:
        # utf-8-sig: the file may have been opened and re-saved by Excel, which
        # adds a BOM that would otherwise become part of the first column name.
        with open(path, "r", encoding="utf-8-sig", newline="",
                  errors="replace") as fh:
            for raw in csv.DictReader(fh):
                if not raw.get("timestamp") or not raw.get("record_id"):
                    continue
                row = dict(raw)
                for k in STAT_KEYS:
                    row[k] = as_int(row.get(k))
                rows.append(row)
    except (OSError, csv.Error, UnicodeError) as exc:
        note(f"  could not read history {path}: {exc}")
        return []
    return rows


def history_is_compatible(path):
    """True unless PATH exists and is some other file we would corrupt.

    The history is opened in append mode, so pointing --csv at an unrelated
    file would quietly staple stat rows onto the end of it. Only append to a
    file that carries our own header.
    """
    if not os.path.isfile(path):
        return True
    try:
        with open(path, "r", encoding="utf-8-sig", newline="",
                  errors="replace") as fh:
            header = next(csv.reader(fh), None)
    except (OSError, csv.Error, UnicodeError):
        return False         # unreadable: cannot prove it is ours, so leave it
    if header is None:
        return True          # empty file, safe to claim
    return [h.strip() for h in header] == CSV_COLUMNS


def append_history(path, rows):
    new_file = not os.path.isfile(path)
    parent = os.path.dirname(os.path.abspath(path))
    if parent and not os.path.isdir(parent):
        note(f"  history directory does not exist: {parent}")
        return False
    if not history_is_compatible(path):
        note(f"  refusing to append: {path} exists and does not carry this "
             "tool's CSV header.")
        note("  pass a different --csv path, or move that file aside.")
        return False
    try:
        with open(path, "a", encoding="utf-8", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=CSV_COLUMNS)
            if new_file:
                w.writeheader()
            for r in rows:
                w.writerow({k: r[k] for k in CSV_COLUMNS})
    except OSError as exc:
        note(f"  could not write history {path}: {exc}")
        return False
    return True


def previous_snapshot(history):
    """The most recent complete run already in the CSV: {record_id: row}."""
    if not history:
        return {}, None
    prev_ts = max(r["timestamp"] for r in history)
    return {r["record_id"]: r for r in history if r["timestamp"] == prev_ts}, prev_ts


# ----------------------------------------------------------------- ascii output

def print_table(headers, rows, aligns, total_row=None):
    widths = [len(h) for h in headers]
    for r in rows + ([total_row] if total_row else []):
        for i, cell in enumerate(r):
            widths[i] = max(widths[i], len(str(cell)))
    border = "+" + "+".join("-" * (w + 2) for w in widths) + "+"

    def line(r):
        cells = []
        for i, cell in enumerate(r):
            s = str(cell)
            cells.append(" " + (s.ljust(widths[i]) if aligns[i] == "l"
                                else s.rjust(widths[i])) + " ")
        return "|" + "|".join(cells) + "|"

    show(border)
    show(line(headers))
    show(border)
    for r in rows:
        show(line(r))
    if total_row:
        show(border)
        show(line(total_row))
    show(border)


def fmt_delta(cur, prev_row, key):
    if not prev_row:
        return ""
    return f"{cur - prev_row.get(key, 0):+,}"


def clip(text, width=TITLE_MAX):
    # Fold to ASCII *before* measuring: an ellipsis expands to three characters
    # and an accent drops one, so widths computed on the raw string would leave
    # the table columns misaligned.
    text = " ".join(ascii_safe(text or "(untitled)").split())
    return text if len(text) <= width else text[:width - 3] + "..."


def render_table(records, prev, prev_ts):
    headers = ["RECORD", "TITLE", "PUBLISHED", "DAYS", "VIEWS", "DELTA_V",
               "DOWNL", "DELTA_D", "U.VIEWS", "U.DOWNL", "DL/DAY"]
    aligns = ["r", "l", "l", "r", "r", "r", "r", "r", "r", "r", "r"]
    rows = []
    for rec in records:
        p = prev.get(rec["record_id"])
        rate = per_day(rec["downloads"], rec["days"])
        rows.append([
            rec["record_id"],
            clip(rec["title"]),
            rec["publication_date"] or "?",
            # A future publication_date (embargo, scheduled release) would
            # otherwise print as a large negative age.
            "?" if rec["days"] is None else max(rec["days"], 0),
            f"{rec['views']:,}",
            fmt_delta(rec["views"], p, "views"),
            f"{rec['downloads']:,}",
            fmt_delta(rec["downloads"], p, "downloads"),
            f"{rec['unique_views']:,}",
            f"{rec['unique_downloads']:,}",
            "?" if rate is None else f"{rate:.2f}",
        ])

    totals = {k: sum(r[k] for r in records) for k in STAT_KEYS}

    # Sum the per-record deltas rather than differencing the totals: a record
    # with no previous row would otherwise book its whole lifetime count as
    # "change since last run".
    matched = [r for r in records if r["record_id"] in prev]
    delta_totals = {k: sum(r[k] - prev[r["record_id"]].get(k, 0) for r in matched)
                    for k in STAT_KEYS}
    total_row = [
        "TOTAL", f"{len(records)} record(s)", "", "",
        f"{totals['views']:,}",
        f"{delta_totals['views']:+,}" if matched else "",
        f"{totals['downloads']:,}",
        f"{delta_totals['downloads']:+,}" if matched else "",
        f"{totals['unique_views']:,}", f"{totals['unique_downloads']:,}", "",
    ]

    print_table(headers, rows, aligns, total_row)
    show("DL/DAY  = downloads divided by days since publication_date "
         "(same-day counts as 1 day).")
    if not prev_ts:
        show("DELTA_* = blank: this is the first run in this history file.")
    elif len(matched) == len(records):
        show(f"DELTA_* = change since the previous run logged at {prev_ts}.")
    else:
        show(f"DELTA_* = change since the previous run logged at {prev_ts}; "
             f"{len(records) - len(matched)} record(s) are new since then and "
             "are excluded from the TOTAL delta.")


