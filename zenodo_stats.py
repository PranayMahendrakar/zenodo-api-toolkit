r"""
Track views/downloads for your published Zenodo records and log them over time.

Every run appends one timestamped row per record to a local CSV, then prints an
ASCII table sorted by downloads with a DELTA column showing what changed since
the previous run, plus a downloads-per-day rate so a record published in 2019
can be compared fairly against one published last week.

READ-ONLY. This script issues GET requests only -- there is no code path here
that can create, modify, publish or delete anything on Zenodo.

    $env:ZENODO_TOKEN="..."                  # PowerShell
    python zenodo_stats.py                   # table + append to history CSV
    python zenodo_stats.py --json            # raw data to stdout instead
    python zenodo_stats.py --html stats.html # also write an HTML dashboard
    python zenodo_stats.py --csv D:\logs\zenodo.csv
    python zenodo_stats.py --no-history      # show only, do not touch the CSV
    python zenodo_stats.py --record 6000557  # public record ids, no token needed
    python zenodo_stats.py --html x.html --force   # overwrite a foreign x.html

Set ZENODO_BASE to https://sandbox.zenodo.org to point at the sandbox.

The only files written are the history CSV (appended to, and only if it carries
this tool's own header) and the optional --html dashboard.

Requests are spaced out to stay inside Zenodo's published budget (60/min as a
guest, 100/min authenticated) and the server's own x-ratelimit headers are
honoured on top of that, so a large collection is fetched slowly rather than
being hammered into a 429.
"""
