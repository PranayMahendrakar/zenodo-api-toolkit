def delta_cls(text):
    if not text:
        return "flat"
    if text.startswith("+") and text != "+0":
        return "up"
    if text.startswith("-"):
        return "down"
    return "flat"


def sparkline(values, width=140, height=30):
    if len(values) < 2:
        return '<span class="nodata">not enough history yet</span>'
    lo, hi = min(values), max(values)
    step = (width - 2) / float(len(values) - 1)
    flat = hi == lo
    pts = []
    for i, v in enumerate(values):
        x = 1 + i * step
        # An unchanged series has no shape to show, so draw it down the middle
        # instead of letting it sit on the bottom edge.
        y = height / 2.0 if flat else height - 1 - (v - lo) * (height - 2) / float(hi - lo)
        pts.append("%.1f,%.1f" % (x, y))
    poly = " ".join(pts)
    area = "1,%d %s %.1f,%d" % (height, poly, width - 1, height)
    lx, ly = pts[-1].split(",")
    return (
        '<svg class="spark" viewBox="0 0 %d %d" width="%d" height="%d" '
        'preserveAspectRatio="none" role="img" aria-label="downloads trend">'
        '<polygon points="%s" fill="rgba(37,99,235,0.14)"/>'
        '<polyline points="%s" fill="none" stroke="#2563eb" stroke-width="1.6" '
        'stroke-linejoin="round" stroke-linecap="round"/>'
        '<circle cx="%s" cy="%s" r="2.4" fill="#2563eb"/></svg>'
        % (width, height, width, height, area, poly, lx, ly)
    )


