MAX_PAGES = 200              # hard stop so a misbehaving pager cannot loop forever
MIN_GAP_GUEST = 1.05         # documented guest budget is 60 requests/minute
MIN_GAP_AUTH = 0.65          # documented authenticated budget is 100 requests/minute
MAX_BACKOFF = 120.0          # never sleep longer than this on a 429
TITLE_MAX = 44

JSON_MODE = False            # when true, chatter goes to stderr

